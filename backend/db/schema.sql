SET client_min_messages = warning;
-- Excalibur v2 — PostgreSQL schema
-- Ported from the SE262 MySQL schema (mysql-init/init.sql).
-- Changes from MySQL:
--   * reserved words `user` / `order` renamed to users / orders
--   * snake_case lower-case identifiers (Categories_id -> category_id, Totalspend -> total_spend, DATE -> sold_date)
--   * MySQL ENUM columns -> PostgreSQL ENUM types
--   * AUTO_INCREMENT -> GENERATED ALWAYS AS IDENTITY
--   * passwords are stored as bcrypt hashes; users have a role column (admin was an .env login before)
--   * the late ALTER TABLE fixes at the end of init.sql are folded into the CREATE TABLEs

DROP VIEW  IF EXISTS game_catalog;
DROP TABLE IF EXISTS game_reviews, transaction_log, order_items, orders, digital_keys, price_history, games, categories, users CASCADE;
DROP TYPE  IF EXISTS key_status, payment_method, payment_status, transaction_type, user_role;

CREATE TYPE key_status       AS ENUM ('available', 'sold', 'reserved');
CREATE TYPE payment_method   AS ENUM ('QR', 'TRUEMONEY');
CREATE TYPE payment_status   AS ENUM ('pending', 'paid', 'failed', 'refunded');
CREATE TYPE transaction_type AS ENUM ('deposit', 'withdrawal', 'purchase', 'refund');
CREATE TYPE user_role        AS ENUM ('customer', 'admin');

CREATE TABLE users (
    user_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(100) NOT NULL UNIQUE,
    email         VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role          user_role     NOT NULL DEFAULT 'customer',
    total_spend   NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    register_date TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE categories (
    category_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    icon        VARCHAR(100) NOT NULL DEFAULT 'Steam-Logo'
);

CREATE TABLE games (
    game_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(150) NOT NULL,
    img          VARCHAR(255),
    release_date DATE,
    avg_rating   NUMERIC(3,2) NOT NULL DEFAULT 0.00,
    description  TEXT,
    category_id  INT REFERENCES categories(category_id) ON DELETE SET NULL
);

CREATE TABLE price_history (
    price_history_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id          INT NOT NULL REFERENCES games(game_id) ON DELETE CASCADE,
    price            NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    recorded_date    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_price_history_game ON price_history (game_id, recorded_date DESC);

CREATE TABLE digital_keys (
    digital_key_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id  INT,
    key_code       VARCHAR(100) NOT NULL UNIQUE,
    game_id        INT NOT NULL REFERENCES games(game_id),
    status         key_status NOT NULL DEFAULT 'available',
    sold_date      TIMESTAMP
);
CREATE INDEX idx_digital_keys_game_status ON digital_keys (game_id, status);

CREATE TABLE orders (
    order_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        INT REFERENCES users(user_id) ON DELETE SET NULL,
    total_amount   NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    payment_method payment_method NOT NULL,
    payment_status payment_status NOT NULL DEFAULT 'pending',
    order_date     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE order_items (
    order_item_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    digital_key_id INT UNIQUE REFERENCES digital_keys(digital_key_id),
    order_id       INT REFERENCES orders(order_id),
    purchase_price NUMERIC(10,2) NOT NULL
);

ALTER TABLE digital_keys
    ADD CONSTRAINT fk_dk_order_item FOREIGN KEY (order_item_id)
    REFERENCES order_items(order_item_id) ON DELETE SET NULL;

CREATE TABLE transaction_log (
    transaction_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       INT REFERENCES orders(order_id) ON DELETE SET NULL,
    user_id        INT REFERENCES users(user_id),
    type           transaction_type NOT NULL,
    amount         NUMERIC(10,2) NOT NULL,
    created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE game_reviews (
    game_review_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        INT REFERENCES users(user_id),
    game_id        INT REFERENCES games(game_id),
    rating         SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment        TEXT,
    review_date    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_game UNIQUE (user_id, game_id)
);

-- One row per game with its current price, platform and available stock.
-- Replaces the correlated sub-queries that were repeated in every MySQL controller.
CREATE VIEW game_catalog AS
SELECT g.game_id,
       g.title,
       g.img,
       g.release_date,
       g.avg_rating,
       g.description,
       g.category_id,
       c.name AS platform_name,
       c.icon AS platform_icon,
       COALESCE(cp.price, 0)::float8 AS price,
       COALESCE(st.stock, 0)::int    AS stock
FROM games g
LEFT JOIN categories c ON c.category_id = g.category_id
LEFT JOIN LATERAL (
    SELECT ph.price FROM price_history ph
    WHERE ph.game_id = g.game_id
    ORDER BY ph.recorded_date DESC, ph.price_history_id DESC
    LIMIT 1
) cp ON TRUE
LEFT JOIN LATERAL (
    SELECT COUNT(*) AS stock FROM digital_keys dk
    WHERE dk.game_id = g.game_id AND dk.status = 'available'
) st ON TRUE;
